type Copy = typeof fr;

const LangContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void; t: Copy } | null>(null);

export function LangProvider({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  const [lang, setLangState] = useState<Lang>("fr");

  useEffect(() => {
    const saved = localStorage.getItem("lm-lang");
    if (saved === "ar" || saved === "fr") setLangState(saved);
  }, []);

  const active: Lang = lang === "ar" && !pathname.startsWith("/admin") ? "ar" : "fr";

  useEffect(() => {
    document.documentElement.lang = active;
    document.documentElement.dir = active === "ar" ? "rtl" : "ltr";
  }, [active]);

  const setLang = (next: Lang) => {
    localStorage.setItem("lm-lang", next);
    setLangState(next);
  };

  return <LangContext.Provider value={{ lang: active, setLang, t: active === "ar" ? ar : fr }}>{children}</LangContext.Provider>;
}

export function useI18n() {
  const value = useContext(LangContext);
  if (!value) throw new Error("Langue hors provider");
  const { lang, t } = value;
  return {
    ...value,
    ar: lang === "ar",
    minutes(seconds: number) {
      const count = Math.max(1, Math.round(seconds / 60));
      return lang === "ar" ? `${count} د` : `${count} min`;
    },
    ago(iso: string, now: string) {
      const a = new Date(iso);
      const b = new Date(now);
      const days = Math.round((Date.UTC(b.getFullYear(), b.getMonth(), b.getDate()) - Date.UTC(a.getFullYear(), a.getMonth(), a.getDate())) / 86_400_000);
      if (lang === "ar") {
        if (days <= 0) return "اليوم";
        if (days === 1) return "أمس";
        return `منذ ${days} أيام`;
      }
      if (days <= 0) return "aujourd'hui";
      if (days === 1) return "hier";
      return `il y a ${days} jours`;
    },
    seenCount(count: number, total: number) {
      if (lang === "ar") {
        if (count <= 0) return `لم تُشاهَد أي حصة من ${total}`;
        return `${count} من ${total} حصص شوهدت`;
      }
      if (count <= 0) return `Aucune leçon vue sur ${total}`;
      if (count === 1) return `1 leçon vue sur ${total}`;
      return `${count} leçons vues sur ${total}`;
    },
    unit(code: string) {
      if (lang === "ar") {
        if (code === "LAN" || code === "PE") return { one: "الدرس", many: "دروس", bare: "درس" };
        if (code === "EX") return { one: "الموضوع", many: "مواضيع", bare: "موضوع" };
        return { one: "الفصل", many: "فصول", bare: "فصل" };
      }
      if (code === "LAN" || code === "PE") return { one: "Leçon", many: "leçons", bare: "leçon" };
      if (code === "EX") return { one: "Sujet", many: "sujets", bare: "sujet" };
      return { one: "Chapitre", many: "chapitres", bare: "chapitre" };
    },
    work(code: string, titre: string, auteur: string, type: string) {
      if (lang !== "ar") return { titre, auteur, type };
      return WORKS[code] ?? { titre, auteur, type };
    },
    lesson(titre: string) {
      if (lang !== "ar") return titre;
      const regional = titre.match(/^Régional (\d{4})/);
      if (regional) return `الجهوي ${regional[1]} · الموضوع والمنهج`;
      return LESSONS[titre] ?? titre;
    },
    examTitle(code: string, fallback: string) {
      if (lang !== "ar") return fallback;
      return EXAM_TITLES[code.toUpperCase()] ?? fallback;
    },
    arrow(back: boolean) {
      if (lang === "ar") return back ? "→" : "←";
      return back ? "←" : "→";
    },
    codeError(message: string) {
      if (lang !== "ar") return message;
      if (message.startsWith("Écris le code")) return t.codeExample;
      if (message.includes("commencent par")) return `${t.codeMissing} ${t.codeStart}`;
      if (message.startsWith("Ce code n'existe pas")) return t.codeMissing;
      return message;
    },
  };
}
